/**
 * @module modules/payment-wechat/app.plugin
 * 职责：Expo Config Plugin——按宿主 androidPackage 自动生成 <package>.wxapi.WXPayEntryActivity 并注册到 AndroidManifest，同时为 iOS 注入微信 queries 白名单与 URL Scheme。
 */
const fs = require('node:fs');
const path = require('node:path');
const { withAndroidManifest, withDangerousMod, withInfoPlist } = require('expo/config-plugins');

const WX_ACTIVITY_TEMPLATE = (pkg) => `package ${pkg}.wxapi

import android.app.Activity
import android.content.Intent
import android.os.Bundle
import com.tencent.mm.opensdk.modelbase.BaseReq
import com.tencent.mm.opensdk.modelbase.BaseResp
import com.tencent.mm.opensdk.openapi.IWXAPIEventHandler
import expo.modules.paymentwechat.WechatPayCallbackRegistry

// Auto-generated by modules/payment-wechat/app.plugin.js during expo prebuild
class WXPayEntryActivity : Activity(), IWXAPIEventHandler {
  override fun onCreate(savedInstanceState: Bundle?) {
    super.onCreate(savedInstanceState)
    WechatPayCallbackRegistry.api?.handleIntent(intent, this)
  }

  override fun onNewIntent(intent: Intent) {
    super.onNewIntent(intent)
    setIntent(intent)
    WechatPayCallbackRegistry.api?.handleIntent(intent, this)
  }

  override fun onReq(req: BaseReq) {}

  override fun onResp(resp: BaseResp) {
    WechatPayCallbackRegistry.resolveResp(resp)
    finish()
  }
}
`;

function withWechatPay(config, options = {}) {
  const appId = options.appId;

  config = withInfoPlist(config, (mod) => {
    const queries = new Set(mod.modResults.LSApplicationQueriesSchemes ?? []);
    queries.add('weixin');
    queries.add('wechat');
    queries.add('weixinulapi');
    mod.modResults.LSApplicationQueriesSchemes = Array.from(queries);

    if (appId) {
      const urlTypes = mod.modResults.CFBundleURLTypes ?? [];
      const exists = urlTypes.some(
        (item) => Array.isArray(item.CFBundleURLSchemes) && item.CFBundleURLSchemes.includes(appId),
      );
      if (!exists) {
        urlTypes.push({ CFBundleURLName: 'weixin', CFBundleURLSchemes: [appId] });
      }
      mod.modResults.CFBundleURLTypes = urlTypes;
    }
    return mod;
  });

  config = withAndroidManifest(config, (mod) => {
    const app = mod.modResults.manifest.application?.[0];
    if (!app) {
      return mod;
    }
    app.activity = app.activity ?? [];
    const activityName = '.wxapi.WXPayEntryActivity';
    const exists = app.activity.some((act) => act.$?.['android:name'] === activityName);
    if (!exists) {
      app.activity.push({
        $: {
          'android:name': activityName,
          'android:exported': 'true',
          'android:launchMode': 'singleTop',
          'android:theme': '@android:style/Theme.Translucent.NoTitleBar',
        },
      });
    }
    return mod;
  });

  config = withDangerousMod(config, [
    'android',
    async (mod) => {
      const pkg = mod.android?.package ?? 'com.enterprise.rntemplate';
      const wxapiDir = path.join(
        mod.modRequest.platformProjectRoot,
        'app/src/main/java',
        ...pkg.split('.'),
        'wxapi',
      );
      fs.mkdirSync(wxapiDir, { recursive: true });
      fs.writeFileSync(
        path.join(wxapiDir, 'WXPayEntryActivity.kt'),
        WX_ACTIVITY_TEMPLATE(pkg),
        'utf8',
      );
      return mod;
    },
  ]);

  return config;
}

module.exports = withWechatPay;
